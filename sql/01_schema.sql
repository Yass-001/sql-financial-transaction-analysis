-- PROJECT: SQL Financial Transaction Analysis
-- FILE: 01_schema.sql
-- DATABASE: PostgreSQL
-- DESCRIPTION: Database schema creation

create database financial_analysis
    with
    owner = postgres
    encoding = 'UTF8'
    template = template0;

create table customers (

    customer_id INTEGER
        generated by default as identity
        primary key,

    customer_name VARCHAR(150)
        not null,

    country VARCHAR(100)
        not null,

    registration_date DATE
        not null,

    risk_category VARCHAR(20)
        not null,

    constraint  chk_customer_risk
        check (
            risk_category in (
                'LOW',
                'MEDIUM',
                'HIGH'
            )
        )

);

create table accounts (

    account_id INTEGER
        generated by default as identity
        primary key,

    customer_id INTEGER
        not null,

    account_type VARCHAR(30)
        not null,

    currency VARCHAR(3)
        not null,

    opened_date DATE
        not null,

    constraint fk_accounts_customers
        foreign key (customer_id)
        references customers(customer_id),

    constraint chk_account_type
        check (
            account_type in (
                'CURRENT',
                'SAVINGS',
                'BUSINESS',
                'CREDIT'
            )
        ),

    constraint chk_account_currency
        check (
            currency ~ '^[A-Z]{3}$'
        )

);

create table counterparties (

    counterparty_id INTEGER
        generated by default as identity
        primary key,

    counterparty_name VARCHAR(150)
        not null,

    country VARCHAR(100),

    business_type VARCHAR(50)
        not null

);

create table transactions (

    transaction_id INTEGER
        generated by default as identity
        primary key,

    account_id INTEGER
        not null,

    transaction_date TIMESTAMP
        not null,

    amount NUMERIC(18,2)
        not null,

    currency VARCHAR(3)
        not null,

    transaction_type VARCHAR(30)
        not null,

    counterparty_id INTEGER,

    country VARCHAR(100),

    status VARCHAR(20)
        not null,

    constraint fk_transactions_accounts
        foreign key (account_id)
        references accounts(account_id),

    constraint fk_transactions_counterparties
        foreign key (counterparty_id)
        references counterparties(counterparty_id),

    constraint chk_transaction_amount
        check (amount > 0),

    constraint chk_transaction_currency
        check (currency ~ '^[A-Z]{3}$'),

    constraint chk_transaction_type
        check (
            transaction_type in (
                'TRANSFER',
                'PAYMENT',
                'DEPOSIT',
                'WITHDRAWAL',
                'FEE'
            )
        ),

    constraint chk_transaction_status
        check (
            status in (
                'COMPLETED',
                'PENDING',
                'FAILED',
                'REVERSED'
            )
        )

);

create table exchange_rates (

    currency VARCHAR(3)
        not null,

    rate_date DATE
        not null,

    rate_to_eur NUMERIC(18,8)
        not null,

    constraint pk_exchange_rates
        primary key (currency, rate_date),

    constraint chk_exchange_currency
        check (currency ~ '^[A-Z]{3}$'),

    constraint chk_exchange_rate
        check (rate_to_eur > 0)

);





